#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*res;
	int		i;

	if (!s)
		return (NULL);
	i = 0;
	res = malloc(sizeof(char) * ft_strlen(s) + 1);
	if (!res)
		return (NULL);
	while (s[i])
	{
		res[i] = s[i];
		i++;
	}
	res[i] = '\0';
	return (res);
}
