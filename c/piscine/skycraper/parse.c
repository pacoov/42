#include "rush.h"

void	parse_clues(char *str, int clues[16])
{
	int	i;
	int	j;

	i = 0;
	j = 0;
	while (j < 16)
	{
		clues[j] = str[i] - '0';
		i += 2;
		j++;
	}
}
